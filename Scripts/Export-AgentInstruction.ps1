#Requires -Version 7.6
<#
.SYNOPSIS
    Generates AGENTS.md, the instruction file for AI agents, from Docs\standards\.

.DESCRIPTION
    Reads the standards files in a fixed order (coding, security, testing, documentation,
    invariants) and joins them into one Markdown file for AI coding agents. Claude Code
    reads it through an import in a local CLAUDE.md; Cursor reads a root AGENTS.md itself.

    The rules are carried as they are written. The script changes only what moving them
    to the repository root requires:
      - each file's title becomes a second-level heading, and its other headings move
        down one level
      - a relative link is rewritten to resolve from the repository root

    Lines inside a fenced code block are never changed. The same source always produces
    the same text, so a static test can compare the committed AGENTS.md with a fresh run.

.PARAMETER RepoRoot
    The repository root. Defaults to the parent of this script's folder (Scripts\).

.PARAMETER Path
    Where to write the file. Nothing is written when this is omitted.

.OUTPUTS
    [PSCustomObject] with Success, Data and Message. Data.Markdown holds the generated
    text whether or not it was written; Data.RuleCount is the number of rules it carries.

.EXAMPLE
    .\Scripts\Export-AgentInstruction.ps1 -Path .\AGENTS.md

    Regenerates AGENTS.md after a change to Docs\standards\.

.EXAMPLE
    (.\Scripts\Export-AgentInstruction.ps1).Data.Markdown

    Returns the text without writing it.

.NOTES
    Copyright © TACE Data Management Inc.
    **Invocation:** Standalone — safe to run with `pwsh -File`; also called by
    Tests\Static\AgentInstruction.Tests.ps1, which fails when the committed AGENTS.md
    differs from a fresh run.
#>
[CmdletBinding(SupportsShouldProcess)]
[OutputType([PSCustomObject])]
param(
    [Parameter()]
    [ValidateNotNullOrEmpty()]
    [string]$RepoRoot = (Split-Path -Path $PSScriptRoot -Parent),

    [Parameter()]
    [ValidateNotNull()]
    [string]$Path = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

try {
    $standardsDir = Join-Path -Path $RepoRoot -ChildPath 'Docs' -AdditionalChildPath 'standards'
    $sources      = @('coding.md', 'security.md', 'testing.md', 'documentation.md', 'invariants.md')
    $rulePattern  = '^- \*\*[A-Z]-\d+\*\* — '

    $out = [System.Collections.Generic.List[string]]::new()
    $out.Add('# Agent Instructions — TACE.Oracle.Admin')
    $out.Add('')
    $out.Add('Generated by `Scripts\Export-AgentInstruction.ps1` from `Docs\standards\`. Do not edit')
    $out.Add('by hand: change the standard, then regenerate. A static test fails when this file')
    $out.Add('does not match the standards.')
    $out.Add('')
    $out.Add('These are the rules this repository is held to. They apply the same way to code')
    $out.Add('written by a person and code generated by an AI. Each rule is one sentence and one')
    $out.Add('example, with an ID and what enforces it: *Linter* and *Test* are checks the gate')
    $out.Add('runs; *Review* needs judgement, and a reviewer checks it.')
    $out.Add('')
    $out.Add('## Checking your work')
    $out.Add('')
    $out.Add('Run `.\Scripts\Invoke-Gate.ps1 -Unit` before you report a change as done. It runs the')
    $out.Add('analyzer, the static tier, secret scanning and the unit tier. A change is done only')
    $out.Add('when every check passes.')

    $ruleCount = 0
    foreach ($name in $sources) {
        $sourcePath = Join-Path -Path $standardsDir -ChildPath $name
        if (-not (Test-Path -LiteralPath $sourcePath)) {
            throw "Standards file not found: Docs\standards\$name"
        }

        $lines   = @(((Get-Content -LiteralPath $sourcePath -Raw) -replace "`r`n", "`n").TrimEnd() -split "`n")
        $inFence = $false
        $seenH1  = $false
        $out.Add('')

        foreach ($line in $lines) {
            if ($line -match '^\s*```') {
                $inFence = -not $inFence
                $out.Add($line)
                continue
            }
            if ($inFence) {
                $out.Add($line)
                continue
            }

            if (-not $seenH1 -and $line -match '^# (.+)$') {
                $seenH1 = $true
                $out.Add("## $($Matches[1])")
                $out.Add('')
                $out.Add("Source: ``Docs\standards\$name``.")
                continue
            }
            if ($line -match '^#{2,} ') {
                $line = "#$line"
            }

            # Links: '../X' is relative to Docs\; a bare 'X.md' is a sibling in Docs\standards\.
            $line = $line -replace '\]\(\.\./([^)]+)\)', '](Docs/$1)'
            $line = $line -replace '\]\(([A-Za-z0-9_-]+\.md)\)', '](Docs/standards/$1)'

            if ($line -match $rulePattern) {
                $ruleCount++
            }
            $out.Add($line)
        }

        if (-not $seenH1) {
            throw "Standards file has no title: Docs\standards\$name"
        }
        if ($inFence) {
            throw "Standards file has an unclosed code block: Docs\standards\$name"
        }
    }

    $markdown = ($out -join "`n") + "`n"

    if ($Path -ne '' -and $PSCmdlet.ShouldProcess($Path, 'Write agent instructions')) {
        [System.IO.File]::WriteAllText($Path, $markdown, [System.Text.UTF8Encoding]::new($false))
    }

    return [PSCustomObject]@{
        Success = $true
        Data    = [PSCustomObject]@{
            Markdown  = $markdown
            RuleCount = $ruleCount
            Sources   = @($sources)
        }
        Message = "$ruleCount rules from $($sources.Count) standards files."
    }
}
catch {
    return [PSCustomObject]@{
        Success = $false
        Data    = $null
        Message = "Agent instruction export failed: $($PSItem.Exception.Message)"
    }
}
